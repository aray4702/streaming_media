// --- RTP parsing for measurement --------------------------------------------

struct RtpInfo {
  bool ok = false;
  uint32_t ssrc = 0;
  uint8_t pt = 0;
  uint16_t seq = 0;
  uint32_t ts = 0;
  size_t payload_off = 0, payload_len = 0;
};

bool IsRtcp(std::span<const uint8_t> d) { return d.size() >= 2 && d[1] >= 192 && d[1] <= 223; }

RtpInfo ParseRtp(std::span<const uint8_t> d) {
  RtpInfo r;
  if (d.size() < 12 || (d[0] >> 6) != 2) return r;
  size_t off = 12 + 4 * static_cast<size_t>(d[0] & 0x0f);
  if (d[0] & 0x10) {
    if (off + 4 > d.size()) return r;
    off += 4 + 4 * ((static_cast<size_t>(d[off + 2]) << 8) | d[off + 3]);
  }
  size_t end = d.size();
  if (d[0] & 0x20) end -= std::min<size_t>(end, d[d.size() - 1]);
  if (off > end) return r;
  r.ok = true;
  r.pt = d[1] & 0x7f;
  r.seq = static_cast<uint16_t>((d[2] << 8) | d[3]);
  r.ts = (static_cast<uint32_t>(d[4]) << 24) | (static_cast<uint32_t>(d[5]) << 16) | (static_cast<uint32_t>(d[6]) << 8) | d[7];
  r.ssrc = (static_cast<uint32_t>(d[8]) << 24) | (static_cast<uint32_t>(d[9]) << 16) | (static_cast<uint32_t>(d[10]) << 8) | d[11];
  r.payload_off = off;
  r.payload_len = end - off;
  return r;
}

// Bytes of the primary (newest) block of an RFC 2198 RED payload.
size_t RedPrimaryBytes(const uint8_t* p, size_t len) {
  size_t off = 0, redundant = 0;
  while (off < len && (p[off] & 0x80)) {
    if (off + 4 > len) return 0;
    redundant += (static_cast<size_t>(p[off + 2] & 0x03) << 8) | p[off + 3];
    off += 4;
  }
  off += 1;
  return len >= off + redundant ? len - off - redundant : 0;
}

