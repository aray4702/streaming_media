// --- Video: the test bench's encoder model as a libwebrtc encoder -----------

struct VideoModel {
  const Scenario* s = nullptr;
  Random rng;
  int64_t frames_captured = 0, frames_encoded = 0, keyframes = 0, bytes = 0;
  int64_t qp_sum = 0, encode_us_sum = 0;  // testbench/encoder_model.h (issue #84).
  int64_t height_sum = 0;                  // Encoded frame heights (quality scaling, issue #84).
  int64_t last_key_us = INT64_MIN / 2;
  int64_t encoder_rate_bps = 0;  // Last SetRates (issue #131 trace).
  int64_t encoder_rate_bps_sum = 0;  // encoder_rate_bps at each captured frame (issue #466).
  int64_t start_us = 0;              // The call's start on the simulated clock: capture times for the size model.
  int64_t keyframe_bytes = 0;    // Total size of the keyframes (issue #333 trace).
  int last_width = 0, last_height = 0;  // Size of the last frame encoded (issue #333 trace).
  // Capture time by the encoder's RTP timestamp, filled by the encoder (issue #339). On the wire the
  // timestamp carries RTPSender's random offset (rtp_sender.cc, timestamp_offset_); the send transport
  // learns it from the first video packet, which belongs to the first frame encoded.
  std::unordered_map<uint32_t, int64_t> capture_us_by_rtp;
  std::optional<uint32_t> first_rtp_ts;  // Encoder RTP timestamp of the first frame encoded.
  std::optional<uint32_t> rtp_ts_offset;  // Wire RTP timestamp minus the encoder's.
  // The trace's rtx_room column (#555): the sender's RTX reservation phase when each frame was handed to
  // VideoStreamEncoder (encoder RTP timestamp -> rtx_room), from the RTCP the send Call takes.
  testbench::RtxAckPhase* rtx_ack = nullptr;
  std::unordered_map<uint32_t, int32_t> frame_rtx_room;
  // Each frame's path by the encoder's RTP timestamp, as the test bench's (issue #510): the encoder sets the capture
  // time and the time it hands the frame on, the send transport the last media packet's send time, the forward link
  // the arrival of its last media or RTX packet, and the renderer the render time.
  std::unordered_map<uint32_t, testbench::VideoFrameTimes> frame_times;
  std::function<sm::Timestamp()> now;  // Time since the call started.
};

// Frame sizes follow the allocated rate with +-20% variation and keyframes
// are 4x larger, as in testbench/call.cc. The payload is the H.264 access
// unit this library sends for that size (model_h264.h, issue #339), and the
// capture time stays in VideoModel::capture_us_by_rtp for the receiver.
// QP (EncodedImage::qp_) and the encode time (timing_) come from the encoder
// model the test bench uses (testbench/encoder_model.h, issue #84).
class ModelEncoder final : public w::VideoEncoder {
 public:
  explicit ModelEncoder(VideoModel* m) : m_(m) {}
  int InitEncode(const w::VideoCodec*, const Settings&) override { return WEBRTC_VIDEO_CODEC_OK; }
  int32_t RegisterEncodeCompleteCallback(w::EncodedImageCallback* cb) override {
    cb_ = cb;
    return WEBRTC_VIDEO_CODEC_OK;
  }
  int32_t Release() override {
    cb_ = nullptr;
    return WEBRTC_VIDEO_CODEC_OK;
  }
  void SetRates(const RateControlParameters& p) override {
    rate_bps_ = p.bitrate.get_sum_bps();
    m_->encoder_rate_bps = rate_bps_;
  }
  int32_t Encode(const w::VideoFrame& frame, const std::vector<w::VideoFrameType>* types) override {
    if (!cb_) return WEBRTC_VIDEO_CODEC_UNINITIALIZED;
    const int64_t capture_us = frame.timestamp_us();
    bool key = types && !types->empty() && (*types)[0] == w::VideoFrameType::kVideoFrameKey;
    if (m_->s->keyframe_interval.us() > 0 && capture_us - m_->last_key_us >= m_->s->keyframe_interval.us()) key = true;
    double per_frame = static_cast<double>(rate_bps_) / 8 / m_->s->video_fps;
    const testbench::EncoderModel::Behaviour behaviour{m_->s->encoder_overshoot, m_->s->scene_change_interval.ms(),
                                                       m_->s->scene_change_frames, m_->s->scene_change_factor};
    const double factor =
        testbench::EncoderModel::DeltaSizeFactor(behaviour, (capture_us - m_->start_us) / 1000, m_->s->video_fps);
    int64_t bytes = static_cast<int64_t>(key ? per_frame * 4 : per_frame * m_->rng.Uniform(0.8, 1.2) * factor);
    bytes = std::max<int64_t>(bytes, 200);
    const std::vector<uint8_t> au = ModelAccessUnit(key, static_cast<size_t>(bytes));
    auto buf = w::EncodedImageBuffer::Create(au.data(), au.size());
    m_->capture_us_by_rtp[frame.rtp_timestamp()] = capture_us;
    m_->frame_times[frame.rtp_timestamp()].capture = sm::Timestamp::Micros(capture_us - m_->start_us);
    if (!m_->first_rtp_ts) m_->first_rtp_ts = frame.rtp_timestamp();
    w::EncodedImage img;
    img.SetEncodedData(buf);
    img._frameType = key ? w::VideoFrameType::kVideoFrameKey : w::VideoFrameType::kVideoFrameDelta;
    img._encodedWidth = static_cast<uint32_t>(frame.width());
    img._encodedHeight = static_cast<uint32_t>(frame.height());
    img.SetRtpTimestamp(frame.rtp_timestamp());
    img.capture_time_ms_ = frame.render_time_ms();
    img.qp_ = testbench::EncoderModel::Qp(bytes, key, frame.width(), frame.height(), m_->s->video_complexity);
    const int64_t encode_us = testbench::EncoderModel::EncodeTimeUs(frame.width(), frame.height(), m_->s->encoder_speed);
    img.timing_.flags = w::VideoSendTiming::kNotTriggered;
    img.timing_.encode_start_ms = capture_us / 1000;
    img.timing_.encode_finish_ms = (capture_us + encode_us) / 1000;
    m_->qp_sum += img.qp_;
    m_->height_sum += frame.height();
    m_->encode_us_sum += encode_us;
    w::CodecSpecificInfo info;
    info.codecType = w::kVideoCodecH264;
    info.codecSpecific.H264.packetization_mode = w::H264PacketizationMode::NonInterleaved;
    info.codecSpecific.H264.temporal_idx = w::kNoTemporalIdx;
    info.codecSpecific.H264.base_layer_sync = false;
    info.codecSpecific.H264.idr_frame = key;
    ++m_->frames_encoded;
    m_->bytes += bytes;
    m_->last_width = frame.width();
    m_->last_height = frame.height();
    if (key) {
      ++m_->keyframes;
      m_->keyframe_bytes += bytes;
      m_->last_key_us = capture_us;
    }
    if (m_->s->encode_delay && encode_us > 0) {
      // `encode_delay on` (issue #84 step 5): the encoder takes the model's
      // encode time, so the encoded callback comes that much later, on the
      // encoder queue, as an asynchronous encoder's would. VideoStreamEncoder
      // then measures the time (OveruseFrameDetector's SendProcessingUsage1
      // reads the clock at OnEncodedImage) and the frame is sent at that time.
      std::weak_ptr<bool> alive = alive_;
      w::TaskQueueBase::Current()->PostDelayedHighPrecisionTask(
          [this, alive, img, info]() mutable {
            if (alive.lock() && cb_) Deliver(img, info);
          },
          w::TimeDelta::Micros(encode_us));
    } else {
      Deliver(img, info);
    }
    return WEBRTC_VIDEO_CODEC_OK;
  }
  EncoderInfo GetEncoderInfo() const override {
    EncoderInfo info;
    info.implementation_name = "sm-encoder-model";
    // Like a software encoder: libwebrtc's frame dropper corrects overshoot,
    // as the test bench's frame dropper does.
    info.has_trusted_rate_controller = false;
    info.is_hardware_accelerated = false;
    // With `quality_scaling on`, an encoder that reports QP and asks for quality
    // scaling with H.264's thresholds and kDefaultMinPixelsPerFrame (issue #84;
    // QualityScalingExperiment's thresholds replace these, see RunWebrtcCall).
    if (m_->s->quality_scaling) {
      info.scaling_settings = ScalingSettings(24, 37);
    } else {
      info.scaling_settings = ScalingSettings::kOff;
    }
    return info;
  }

 private:
  // Hands the encoded frame to VideoStreamEncoder: the test bench's `submitted` time (issue #510).
  void Deliver(const w::EncodedImage& img, const w::CodecSpecificInfo& info) {
    if (m_->now) m_->frame_times[img.RtpTimestamp()].submitted = m_->now();
    if (m_->rtx_ack) m_->frame_rtx_room[img.RtpTimestamp()] = m_->rtx_ack->Room();
    cb_->OnEncodedImage(img, &info);
  }

  VideoModel* m_;
  w::EncodedImageCallback* cb_ = nullptr;
  uint32_t rate_bps_ = 0;
  std::shared_ptr<bool> alive_ = std::make_shared<bool>(true);  // For delayed encoded callbacks.
};

