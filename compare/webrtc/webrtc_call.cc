// Records the sender's GoogCC events (issue #149) in this library's BweTraceRow layout:
// RtcEventBweUpdateDelayBased (delay_based_bwe.cc) and RtcEventBweUpdateLossBased
// (send_side_bandwidth_estimation.cc). LossBasedBweV2's own state (LossBasedState, the
// loss-limited estimate) has no event or public accessor in the prebuilt libwebrtc, so
// those columns stay empty here.
class BweTraceLog final : public w::RtcEventLog {
 public:
  BweTraceLog(std::function<int64_t()> now_us, std::vector<cc::BweTraceRow>* rows) : now_us_(std::move(now_us)), rows_(rows) {}
  bool StartLogging(std::unique_ptr<w::RtcEventLogOutput>, int64_t) override { return true; }
  void StopLogging() override {}
  void Log(std::unique_ptr<w::RtcEvent> event) override {
    cc::BweTraceRow r;
    r.time_us = now_us_();
    switch (event->GetType()) {
      case w::RtcEvent::Type::BweUpdateDelayBased: {
        const auto* e = static_cast<const w::RtcEventBweUpdateDelayBased*>(event.get());
        r.kind = cc::BweTraceRow::Kind::kDelayBased;
        r.bitrate_bps = e->bitrate_bps();
        r.detector = static_cast<int>(e->detector_state());  // kBwNormal, kBwUnderusing, kBwOverusing: as BandwidthUsage here.
        break;
      }
      case w::RtcEvent::Type::BweUpdateLossBased: {
        const auto* e = static_cast<const w::RtcEventBweUpdateLossBased*>(event.get());
        r.kind = cc::BweTraceRow::Kind::kLossBased;
        r.bitrate_bps = e->bitrate_bps();
        r.fraction_loss = e->fraction_loss();
        r.packets = e->total_packets();
        break;
      }
      default:
        return;
    }
    rows_->push_back(r);
  }

 private:
  std::function<int64_t()> now_us_;
  std::vector<cc::BweTraceRow>* rows_;
};

// The sender's network controller: libwebrtc's GoogCC, exactly as RtpTransportControllerSend creates it without an
// override (GoogCcNetworkControllerFactory with rfc_8888_feedback_negotiated false), with every call forwarded
// unchanged. Each transport feedback is also replayed through libwebrtc's own InterArrivalDelta and TrendlineEstimator
// the way DelayBasedBwe::IncomingPacketFeedback feeds them (sorted by receive time, 5 ms groups, a reset after 2 s
// without feedback or when GoogCC makes a new DelayBasedBwe), giving one kDetector row per group (issue #152). After
// the live controller has taken the same feedback, fraction_loss on that feedback's rows says whether the replica
// still matches the live detector (0) or not (1): its modified trend, threshold, delta count and state.
class DetectorTraceController final : public w::NetworkControllerInterface {
 public:
  DetectorTraceController(std::unique_ptr<w::NetworkControllerInterface> inner, const w::Environment& env,
                          std::function<int64_t()> now_us, std::vector<cc::BweTraceRow>* rows, w::Timestamp t0)
      : inner_(std::move(inner)), env_(env), now_us_(std::move(now_us)), rows_(rows), t0_(t0) {}
  w::NetworkControlUpdate OnNetworkAvailability(w::NetworkAvailability m) override { return inner_->OnNetworkAvailability(m); }
  w::NetworkControlUpdate OnNetworkRouteChange(w::NetworkRouteChange m) override { return inner_->OnNetworkRouteChange(m); }
  w::NetworkControlUpdate OnProcessInterval(w::ProcessInterval m) override { return inner_->OnProcessInterval(m); }
  w::NetworkControlUpdate OnRemoteBitrateReport(w::RemoteBitrateReport m) override { return inner_->OnRemoteBitrateReport(m); }
  w::NetworkControlUpdate OnRoundTripTimeUpdate(w::RoundTripTimeUpdate m) override { return inner_->OnRoundTripTimeUpdate(m); }
  w::NetworkControlUpdate OnSentPacket(w::SentPacket m) override { return inner_->OnSentPacket(m); }
  w::NetworkControlUpdate OnReceivedPacket(w::ReceivedPacket m) override { return inner_->OnReceivedPacket(m); }
  w::NetworkControlUpdate OnStreamsConfig(w::StreamsConfig m) override { return inner_->OnStreamsConfig(m); }
  w::NetworkControlUpdate OnTargetRateConstraints(w::TargetRateConstraints m) override {
    return inner_->OnTargetRateConstraints(m);
  }
  w::NetworkControlUpdate OnTransportLossReport(w::TransportLossReport m) override { return inner_->OnTransportLossReport(m); }
  w::NetworkControlUpdate OnNetworkStateEstimate(w::NetworkStateEstimate m) override {
    return inner_->OnNetworkStateEstimate(m);
  }
  bool SupportsEcnAdaptation() const override { return inner_->SupportsEcnAdaptation(); }

  w::NetworkControlUpdate OnTransportPacketsFeedback(w::TransportPacketsFeedback m) override {
    if (m.packet_feedbacks.empty()) return inner_->OnTransportPacketsFeedback(std::move(m));  // GoogCC returns early.
    const size_t first_row = rows_->size();
    Replay(m);
    w::NetworkControlUpdate u = inner_->OnTransportPacketsFeedback(std::move(m));
    using P = w::GoogCcStatePrinter;
    const w::TrendlineEstimator* live = P::Detector(P::Delay(inner_.get()));
    const bool match = detector_ && P::ModifiedTrend(live) == P::ModifiedTrend(detector_.get()) &&
                       P::Threshold(live) == P::Threshold(detector_.get()) &&
                       P::NumDeltas(live) == P::NumDeltas(detector_.get()) && live->State() == detector_->State();
    for (size_t i = first_row; i < rows_->size(); ++i) (*rows_)[i].fraction_loss = match ? 0 : 1;
    return u;
  }

 private:
  void Replay(const w::TransportPacketsFeedback& m) {
    constexpr w::TimeDelta kStreamTimeOut = w::TimeDelta::Seconds(2);   // delay_based_bwe.cc
    constexpr w::TimeDelta kSendTimeGroupLength = w::TimeDelta::Millis(5);
    const w::DelayBasedBwe* bwe = w::GoogCcStatePrinter::Delay(inner_.get());
    if (bwe != bwe_) {  // OnNetworkRouteChange made a new DelayBasedBwe, which resets on its first packet.
      bwe_ = bwe;
      last_seen_packet_ = w::Timestamp::MinusInfinity();
    }
    for (const w::PacketResult& p : m.SortedByReceiveTime()) {
      if (last_seen_packet_.IsInfinite() || m.feedback_time - last_seen_packet_ > kStreamTimeOut) {
        inter_arrival_ = std::make_unique<w::InterArrivalDelta>(kSendTimeGroupLength);
        detector_ = std::make_unique<w::TrendlineEstimator>(env_.field_trials(), nullptr);
      }
      last_seen_packet_ = m.feedback_time;
      w::TimeDelta send_delta = w::TimeDelta::Zero(), recv_delta = w::TimeDelta::Zero();
      int size_delta = 0;
      const bool calculated = inter_arrival_->ComputeDeltas(p.sent_packet.send_time, p.receive_time, m.feedback_time,
                                                            p.sent_packet.size.bytes(), &send_delta, &recv_delta,
                                                            &size_delta);
      detector_->Update(recv_delta.ms<double>(), send_delta.ms<double>(), p.sent_packet.send_time.ms(),
                        p.receive_time.ms(), p.sent_packet.size.bytes(), calculated);
      if (!calculated) continue;
      cc::BweTraceRow r;
      r.time_us = now_us_();
      r.kind = cc::BweTraceRow::Kind::kDetector;
      r.detector = static_cast<int>(detector_->State());
      r.packets = w::GoogCcStatePrinter::NumDeltas(detector_.get());
      r.modified_trend = w::GoogCcStatePrinter::ModifiedTrend(detector_.get());
      r.threshold = w::GoogCcStatePrinter::Threshold(detector_.get());
      r.send_delta_ms = send_delta.ms<double>();
      r.recv_delta_ms = recv_delta.ms<double>();
      r.send_ms = static_cast<double>((p.sent_packet.send_time - t0_).ms());
      r.arrival_ms = static_cast<double>(p.receive_time.ms());  // The receiver's clock, as the feedback carries it.
      rows_->push_back(r);
    }
  }

  std::unique_ptr<w::NetworkControllerInterface> inner_;
  w::Environment env_;
  std::function<int64_t()> now_us_;
  std::vector<cc::BweTraceRow>* rows_;
  const w::DelayBasedBwe* bwe_ = nullptr;
  w::Timestamp last_seen_packet_ = w::Timestamp::MinusInfinity();
  std::unique_ptr<w::InterArrivalDelta> inter_arrival_;
  std::unique_ptr<w::TrendlineEstimator> detector_;
  w::Timestamp t0_;  // Call start, so send_ms is call-relative like ours.
};

