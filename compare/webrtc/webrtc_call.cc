Report RunWebrtcCall(const Scenario& s, const testbench::RunOptions& opt) {
  w::LogMessage::LogToDebug(w::LS_NONE);
  w::LogMessage::SetLogToStderr(false);
  Report rep;
  rep.scenario = s;

  // RTCPSender seeds random_ from this clock (rtcp_sender.cc:130), so the clock at the start picks the RTCP schedule.
  // Each seed starts at its own time (#399); `compare_clock_start` fixes it for every seed (#390). The test bench
  // seeds its RtcpEngines with the same time (RtcpRandomSeed), so both draw the same schedule (#517).
  const int64_t t0_s = testbench::CallClockStartSeconds(s);
  const w::Timestamp t0 = w::Timestamp::Seconds(t0_s);
  SimTime sim(t0);
  w::ScopedYieldPolicy yield_policy(&sim);
  auto rel = [&](w::Timestamp t) { return sm::Timestamp::Micros((t - t0).us()); };
  w::EnvironmentFactory env_factory;
  env_factory.Set(sim.clock());
  env_factory.Set(static_cast<w::TaskQueueFactory*>(&sim));
  const w::Environment env = env_factory.Create();
  // The sender's Environment carries the event log sink that records its GoogCC updates.
  BweTraceLog bwe_log([&] { return (sim.Now() - t0).us(); }, &rep.bwe_trace);
  w::EnvironmentFactory sender_env_factory;
  sender_env_factory.Set(sim.clock());
  sender_env_factory.Set(static_cast<w::TaskQueueFactory*>(&sim));
  if (opt.bwe_trace) sender_env_factory.Set(static_cast<w::RtcEventLog*>(&bwe_log));
  // QualityScalingExperiment (on by default) gives H.264 the QP thresholds
  // 24/37 (rtc_base/experiments/quality_scaling_experiment.cc; issue #84).
  // The string is the experiment's default with 24/37 in the Generic slot as
  // well, from when the model encoder reported the Generic codec; since it
  // reports H.264 (issue #339), only the H.264 slot is read.
  if (s.quality_scaling) {
    sender_env_factory.Set(std::make_unique<w::FieldTrials>(
        "WebRTC-Video-QualityScaling/Enabled-29,95,149,205,24,37,24,37,0.9995,0.9999,1/"));
  }
  // `host_rtt` (issues #892, #911): libwebrtc's GoogCC takes the same host RTT from the same time as ours, when
  // its arithmetic on the RTT stays defined. Its unit operators are plain int64 adds and multiplies
  // (`RelativeUnit::operator+`, rtc_base/units/unit_base.h:209-219), and GoogCC adds to the RTT and doubles the
  // sum (`(rtt_ + 100 ms) * 2`, aimd_rate_control.cc:200-202; `kBweDecreaseInterval + last_round_trip_time_`,
  // send_side_bandwidth_estimation.cc:500). The tightest is the doubled sum, defined up to
  // rtt = INT64_MAX / 2 - 100 ms (issue #921's audit), after the RTT is rounded to 1 ms (HostRttValue, as
  // rtp_transport_controller_send.cc:571; up to 500 us more). A larger host RTT is signed-overflow UB there. Such
  // an RTT (issue_451_host_rtt_near_limit, which checks our overflow guards) is not given to libwebrtc: comparing
  // against undefined behaviour measures nothing (window decision on #904). issue_921_host_rtt_under_limit feeds
  // one 100 ms under the limit.
  constexpr int64_t kMaxDefinedHostRttUs = std::numeric_limits<int64_t>::max() / 2 - 100'000 - 500;
  std::optional<std::pair<w::Timestamp, w::TimeDelta>> host_rtt;
  if (s.host_rtt && s.host_rtt->second.us() <= kMaxDefinedHostRttUs) {
    host_rtt.emplace(t0 + w::TimeDelta::Micros(s.host_rtt->first.us()), w::TimeDelta::Micros(s.host_rtt->second.us()));
  }
  // Without --bwe-trace the factory only carries the host RTT: no detector replay, no rows.
  DetectorTraceFactory detector_trace([&] { return (sim.Now() - t0).us(); }, opt.bwe_trace ? &rep.bwe_trace : nullptr,
                                      t0, host_rtt);
  const w::Environment sender_env = sender_env_factory.Create();
  QualityScalerLog qs_log([&] { return (sim.Now() - t0).us(); });
  if (opt.video_trace && s.video && s.quality_scaling) qs_log.Start();

  auto sender_q = sim.CreateTaskQueue("sender", w::TaskQueueFactory::Priority::kNormal);
  auto receiver_q = sim.CreateTaskQueue("receiver", w::TaskQueueFactory::Priority::kNormal);
  auto net_q = sim.CreateTaskQueue("network", w::TaskQueueFactory::Priority::kNormal);
  auto run_on = [&](w::TaskQueueBase* q, std::function<void()> fn) {
    bool done = false;
    q->PostTask([&] {
      fn();
      done = true;
    });
    sim.RunReady();
    RTC_CHECK(done);
  };

  // --- Links ----------------------------------------------------------------
  testbench::LinkTimeline links(s);
  const testbench::LinkState& fwd_state = links.forward();
  sim::NetworkLink<Pkt> forward(fwd_state.cfg, s.seed);
  if (opt.link_trace) forward.EnableTrace();
  sim::NetworkLink<Pkt> reverse(links.reverse().cfg, s.seed + 1000003);
  if (opt.link_trace) reverse.EnableTrace();
  // Applies the scenario's link changes due by `now`. The tick does it first thing, but SimTime runs its queues in
  // creation order, so a libwebrtc task due at the same millisecond as the tick (the receiver's transport feedback
  // timer, the pacer) can run before it and send on the old link. Each transport calls this before it sends, so a
  // packet sent at or after a change sees it, as in the test bench, where every send follows the tick's Advance.
  // Issue #151: the feedback libwebrtc's receiver sent at 12.000 s crossed a reverse link that goes down at 12 s, and
  // its 50 ms newer ack decided where the sender's congestion-window drops started.
  auto advance_links = [&](sm::Timestamp now) {
    auto [fwd_changed, rev_changed] = links.Advance(now - sm::Timestamp::Micros(0));
    if (fwd_changed) forward.SetConfig(fwd_state.cfg);
    if (rev_changed) reverse.SetConfig(links.reverse().cfg);
  };

  // --- Calls ------------------------------------------------------------------
  w::FakeAudioDeviceModule send_adm, recv_adm;
  auto make_audio_state = [](w::AudioDeviceModule* adm) {
    w::AudioState::Config c;
    c.audio_mixer = w::AudioMixerImpl::Create();
    c.audio_device_module = w::scoped_refptr<w::AudioDeviceModule>(adm);
    return w::AudioState::Create(c);
  };
  w::scoped_refptr<w::AudioState> send_audio_state = make_audio_state(&send_adm);
  w::scoped_refptr<w::AudioState> recv_audio_state = make_audio_state(&recv_adm);

  std::unique_ptr<w::Call> send_call, recv_call;
  auto make_call = [&](const w::Environment& call_env, w::scoped_refptr<w::AudioState> audio_state) {
    w::CallConfig c = w::CallConfig::CreateSingleThreaded(call_env);
    // BitrateConstraints hold int bps: a larger finite rate saturates at INT_MAX, as this library's
    // cc::ConvertConstraints does (#464), instead of wrapping; an infinite rate stays -1 ("none").
    const auto int_bps = [](auto r) {
      return r.IsFinite() ? static_cast<int>(std::min<int64_t>(r.bps(), std::numeric_limits<int>::max())) : -1;
    };
    c.bitrate_config.min_bitrate_bps = int_bps(s.min_rate);
    c.bitrate_config.start_bitrate_bps = int_bps(s.start_rate);
    c.bitrate_config.max_bitrate_bps = int_bps(s.max_rate);
    c.audio_state = audio_state;
    // The sender's GoogCC behind the detector trace (issue #152), and behind the host RTT whenever the scenario has
    // one, traced or not (issue #892: the metric runs don't trace, and before this the host RTT reached libwebrtc
    // only on traced runs). The receiver's controller sends nothing that matters.
    if ((opt.bwe_trace || host_rtt) && &call_env == &sender_env) c.network_controller_factory = &detector_trace;
    return w::Call::Create(std::move(c));
  };
  run_on(sender_q.get(), [&] { send_call = make_call(sender_env, send_audio_state); });
  run_on(receiver_q.get(), [&] { recv_call = make_call(env, recv_audio_state); });

  const std::vector<w::RtpExtension> extensions = {
      w::RtpExtension(w::RtpExtension::kTransportSequenceNumberUri, kTransportSeqExtId)};
  const w::RtpHeaderExtensionMap extension_map(extensions);

  // --- Measurement state ----------------------------------------------------
  VideoModel model;
  model.s = &s;
  model.rng = Random(s.seed + 13);
  model.start_us = t0.us();
  model.now = [&] { return rel(sim.Now()); };
  testbench::RtxAckPhase rtx_ack(kVideoSsrc, kRtxSsrc, s.nack);
  std::vector<testbench::AudioSendRow> audio_reports;  // Each audio report block the sender received (issue #484).
  if (opt.link_trace) model.rtx_ack = &rtx_ack;
  // The last media or RTX packet of a frame (RFC 4588 keeps the original RTP timestamp) before it renders marks it
  // complete, as in testbench/call.cc (issue #510).
  auto frame_complete = [&](uint32_t wire_ts, sm::Timestamp at) {
    if (!model.rtp_ts_offset) return;
    auto ft = model.frame_times.find(wire_ts - *model.rtp_ts_offset);
    if (ft != model.frame_times.end() && !ft->second.rendered.IsFinite()) ft->second.complete = at;
  };
  int64_t w_send = 0, w_good = 0;
  testbench::FirstDelivery first_delivery;
  testbench::RepairMeter repair;  // Issue #509: the repair metrics by the test bench's rule.
  // VideoReceiveStream does not expose the packets its ULPFEC receiver recovers, so the harness runs libwebrtc's
  // UlpfecReceiver on the same input: every RED packet that arrives on the video SSRC, in arrival order, as
  // RtpVideoStreamReceiver2::ParseAndHandleEncapsulatingHeader feeds its own (rtp_video_stream_receiver2.cc).
  // RTX-restored RED packets are left out: they are recovered() there, and UlpfecReceiver::ProcessReceivedFec
  // never passes a recovered packet to DecodeFec (ulpfec_receiver.cc), so they recover nothing.
  FecRecoveredSeqs fec_tap_sink(repair);
  std::unique_ptr<w::UlpfecReceiver> fec_tap;
  if (s.video && s.fec) fec_tap = std::make_unique<w::UlpfecReceiver>(kVideoSsrc, kUlpfecPt, &fec_tap_sink, sim.clock());
  std::optional<uint32_t> audio_ts0;
  std::vector<double> video_e2e, rtt_samples, queue_samples, jb_delay;
  testbench::AudioNetDelayMeter audio_net_delay;
  testbench::FirstAudioMeter audio_first;  // Issue #510: as testbench/call.cc.
  sm::Timestamp video_first = sm::Timestamp::MinusInfinity();
  sm::Timestamp last_render = sm::Timestamp::MinusInfinity();
  // Frames rendered and the largest render gap, per second of render time (issue #333 trace).
  struct RenderSecond {
    int rendered = 0;
    double max_gap_ms = 0;
  };
  std::vector<RenderSecond> render_by_second;
  // Cumulative receive-side frame counters at the end of each second (issue #437).
  struct RxSecond {
    int64_t t_ms = 0, complete = 0, decoded = 0, dropped = 0;
  };
  std::vector<RxSecond> rx_by_second;
  video::FreezeDetector freezes;
  testbench::AvSyncMeter av_sync;  // Issue #63.
  int64_t frames_rendered = 0, w_frames = 0;
  double last_video_delay = 0;
  testbench::StretchMeter stretch;  // Issue #510: as testbench/call.cc.
  uint64_t w_conceal = 0, w_played = 0;  // Audio samples.
  testbench::ConcealmentMeter concealment(kAudioRate);  // Issue #372: as testbench/call.cc.
  double audio_buffer_ms = 0;
  w::AudioReceiveStreamInterface::Stats prev_audio;

  // --- Transports -------------------------------------------------------------
  LinkTransport send_transport([&](std::span<const uint8_t> data, bool rtcp, const w::PacketOptions& o) {
    const w::Timestamp now = sim.Now();
    advance_links(rel(now));
    const int64_t wire = static_cast<int64_t>(data.size()) + kUdpIpOverhead;
    // Counted the way the test bench counts: by SSRC, and padding is a packet with no payload.
    sm::sim::LinkKind link_kind = sm::sim::LinkKind::kOther;
    int32_t trace_seq = -1;
    if (!rtcp && !IsRtcp(data)) {
      w::SentPacketInfo sent(o.packet_id, now.ms());
      sent.info.included_in_feedback = o.included_in_feedback;
      sent.info.included_in_allocation = o.included_in_allocation;
      sent.info.packet_size_bytes = data.size();
      sent.info.packet_type = w::PacketType::kData;
      sender_q->PostTask([&, sent] { send_call->OnSentPacket(sent); });
      w_send += wire;
      RtpInfo r = ParseRtp(data);
      if (r.ok) trace_seq = r.seq;
      if (r.ok && r.payload_len == 0 && (r.ssrc == kAudioSsrc || r.ssrc == kVideoSsrc || r.ssrc == kRtxSsrc)) {
        link_kind = sm::sim::LinkKind::kPadding;
      }
      if (r.ok && r.payload_len > 0) {
        const uint8_t* payload = data.data() + r.payload_off;
        if (r.ssrc == kAudioSsrc) {
          if (opt.link_trace) testbench::TraceAudioRtp(data, rel(now).us(), kAudioSsrc, rep.audio_send_trace);
          repair.OnSent(sm::sim::LinkKind::kAudio, data.size(), 0, 0);
          if (!audio_ts0) audio_ts0 = r.ts;
          link_kind = sm::sim::LinkKind::kAudio;
        } else if (r.ssrc == kVideoSsrc) {
          if (!model.rtp_ts_offset && model.first_rtp_ts) model.rtp_ts_offset = r.ts - *model.first_rtp_ts;
          bool fec = r.pt == kRedPt && (payload[0] & 0x7f) == kUlpfecPt;
          link_kind = fec ? sm::sim::LinkKind::kFec : sm::sim::LinkKind::kVideo;
          repair.OnSent(link_kind, data.size(), r.seq, (now - t0).ms());
          if (!fec && model.rtp_ts_offset) {
            auto ft = model.frame_times.find(r.ts - *model.rtp_ts_offset);
            if (ft != model.frame_times.end()) ft->second.last_sent = rel(now);
          }
        } else if (r.ssrc == kRtxSsrc && r.payload_len > 2) {
          link_kind = sm::sim::LinkKind::kRtx;
          repair.OnSent(link_kind, data.size(), 0, 0);
        } else if (r.ssrc == kRtxSsrc) {
          link_kind = sm::sim::LinkKind::kPadding;  // RTX header only (no retransmitted payload).
        }
      }
    }
    // The frame trace's RTP fields (issue #437), as the test bench writes them.
    int64_t trace_ts = -1;
    int32_t trace_marker = -1, trace_osn = -1, trace_key = -1, trace_header = -1, trace_rtx_room = -1;
    if (opt.link_trace && trace_seq >= 0) {
      trace_header = testbench::TraceHeaderBytes(data, wire, kRedPt);
      const RtpInfo r = ParseRtp(data);
      trace_ts = r.ts;
      trace_marker = (data[1] & 0x80) ? 1 : 0;
      if (r.ssrc == kRtxSsrc && r.payload_len >= 2) {
        trace_osn = (data[r.payload_off] << 8) | data[r.payload_off + 1];
      }
      if (link_kind == sm::sim::LinkKind::kVideo) {
        // Behind RED, the primary block follows a one-byte header (FEC packets are kFec, not kVideo).
        const size_t skip = r.pt == kRedPt ? 1 : 0;
        const std::span<const uint8_t> payload =
            r.payload_len > skip ? data.subspan(r.payload_off + skip, r.payload_len - skip) : std::span<const uint8_t>();
        trace_key = sm::rtp::H264Depacketizer::Parse(payload).keyframe ? 1 : 0;
        if (model.rtp_ts_offset) {
          auto it = model.frame_rtx_room.find(r.ts - *model.rtp_ts_offset);
          if (it != model.frame_rtx_room.end()) trace_rtx_room = it->second;
        }
      }
    }
    forward.Send(rel(now), Pkt{std::vector<uint8_t>(data.begin(), data.end()), rtcp || IsRtcp(data), false},
                 DataSize::Bytes(wire), link_kind, trace_seq);
    forward.AnnotateLastTrace(trace_ts, trace_marker, trace_osn, trace_key, trace_header, trace_rtx_room);
  });
  LinkTransport recv_transport([&](std::span<const uint8_t> data, bool rtcp, const w::PacketOptions&) {
    advance_links(rel(sim.Now()));
    reverse.Send(rel(sim.Now()), Pkt{std::vector<uint8_t>(data.begin(), data.end()), rtcp || IsRtcp(data), false},
                 DataSize::Bytes(static_cast<int64_t>(data.size()) + kUdpIpOverhead));
  });

  // --- Streams ----------------------------------------------------------------
  ModelEncoderFactory encoder_factory(&model);
  ModelDecoderFactory decoder_factory;
  auto allocator_factory = w::CreateBuiltinVideoBitrateAllocatorFactory();
  ModelSource source(s.video_width, s.video_height);
  RenderSink renderer([&](const w::VideoFrame& f) {
    const sm::Timestamp now = rel(sim.Now());
    freezes.OnFrameRendered(now);
    if (opt.video_trace && now.us() >= 0) {
      const size_t sec = static_cast<size_t>(now.us() / 1000000);
      if (render_by_second.size() <= sec) render_by_second.resize(sec + 1);
      ++render_by_second[sec].rendered;
      if (last_render.IsFinite())
        render_by_second[sec].max_gap_ms =
            std::max(render_by_second[sec].max_gap_ms, static_cast<double>((now - last_render).us()) / 1000.0);
    }
    ++frames_rendered;
    ++w_frames;
    if (!video_first.IsFinite()) video_first = now;
    last_render = now;
    auto it = model.rtp_ts_offset ? model.capture_us_by_rtp.find(f.rtp_timestamp() - *model.rtp_ts_offset)
                                  : model.capture_us_by_rtp.end();
    if (model.rtp_ts_offset) {
      auto ft = model.frame_times.find(f.rtp_timestamp() - *model.rtp_ts_offset);
      if (ft != model.frame_times.end()) ft->second.rendered = now;
    }
    if (it != model.capture_us_by_rtp.end()) {
      av_sync.OnVideoRendered(now, sm::Timestamp::Micros(it->second - t0.us()));
      last_video_delay = static_cast<double>(sim.Now().us() - it->second) / 1000.0;
      video_e2e.push_back(last_video_delay);
      model.capture_us_by_rtp.erase(it);
    }
  });

  OpusEncodeRows opus_encode_rows;  // Issue #547; outlives the send stream, which owns the encoder.
  w::AudioSendStream* audio_send = nullptr;
  w::VideoSendStream* video_send = nullptr;
  w::AudioReceiveStreamInterface* audio_recv = nullptr;
  w::VideoReceiveStreamInterface* video_recv = nullptr;

  run_on(sender_q.get(), [&] {
    if (s.audio) {
      w::AudioSendStream::Config c(&send_transport);
      c.rtp.ssrc = kAudioSsrc;
      c.rtp.c_name = kSenderCname;
      c.rtp.extensions = extensions;
      // Chrome's default Opus parameters.
      c.send_codec_spec = w::AudioSendStream::Config::SendCodecSpec(
          kOpusPt, {"opus", 48000, 2, {{"minptime", "10"}, {"useinbandfec", "1"}}});
      c.send_codec_spec->target_bitrate_bps = static_cast<int>(s.audio_bitrate.bps());
      if (s.red) c.send_codec_spec->red_payload_type = kAudioRedPt;
      c.encoder_factory = opt.link_trace ? w::scoped_refptr<w::AudioEncoderFactory>(
                                               w::make_ref_counted<TracedAudioEncoderFactory>(&opus_encode_rows))
                                         : w::CreateBuiltinAudioEncoderFactory();
      c.min_bitrate_bps = c.max_bitrate_bps = static_cast<int>(s.audio_bitrate.bps());
      c.include_in_congestion_control_allocation = true;
      audio_send = send_call->CreateAudioSendStream(c);
    }
    if (s.video) {
      w::VideoSendStream::Config c(&send_transport);
      c.rtp.payload_name = "H264";
      c.rtp.payload_type = kVideoPt;
      c.rtp.ssrcs = {kVideoSsrc};
      c.rtp.c_name = kSenderCname;
      c.rtp.extensions = extensions;
      // `video_max_payload` (issue #257): the same whole-packet limit this library's sender uses,
      // payload plus the 12-byte fixed header, clamped to the 100-1500 bytes
      // RTPSender::SetMaxRtpPacketSize accepts (rtp_sender.cc:307-312), as rtp::RtpSender clamps it.
      // Scenarios that leave it at the default keep libwebrtc's own (kDefaultMaxPacketSize, 1460).
      if (s.video_max_payload != Scenario{}.video_max_payload) {
        c.rtp.max_packet_size = std::clamp<size_t>(s.video_max_payload + 12, 100, 1500);
      }
      if (s.nack) {
        c.rtp.nack.rtp_history_ms = 1000;
        c.rtp.rtx.payload_type = kRtxPt;
        c.rtp.rtx.ssrcs = {kRtxSsrc};
      }
      if (s.fec) {
        c.rtp.ulpfec.red_payload_type = kRedPt;
        c.rtp.ulpfec.ulpfec_payload_type = kUlpfecPt;
        if (s.nack) c.rtp.ulpfec.red_rtx_payload_type = kRtxRedPt;
      }
      c.encoder_settings.encoder_factory = &encoder_factory;
      c.encoder_settings.bitrate_allocator_factory = allocator_factory.get();
      w::VideoEncoderConfig ec;
      ec.codec_type = w::kVideoCodecH264;
      ec.content_type = w::VideoEncoderConfig::ContentType::kRealtimeVideo;
      ec.video_format = ModelH264Format();
      ec.number_of_streams = 1;
      ec.simulcast_layers = std::vector<w::VideoStream>(1);
      ec.simulcast_layers[0].max_framerate = s.video_fps;
      ec.simulcast_layers[0].min_bitrate_bps = static_cast<int>(s.video_min.bps());
      ec.max_bitrate_bps = static_cast<int>(s.video_max.bps());
      ec.frame_drop_enabled = true;
      video_send = send_call->CreateVideoSendStream(std::move(c), std::move(ec));
      // A camera: MAINTAIN_FRAMERATE when the quality scaler is on (issue #84),
      // otherwise no adaptation.
      video_send->SetSource(&source, s.quality_scaling ? w::DegradationPreference::MAINTAIN_FRAMERATE
                                                       : w::DegradationPreference::DISABLED);
    }
  });
  run_on(receiver_q.get(), [&] {
    if (s.audio) {
      w::AudioReceiveStreamInterface::Config c;
      c.rtcp_send_transport = &recv_transport;
      c.rtp.remote_ssrc = kAudioSsrc;
      c.decoder_factory = w::CreateBuiltinAudioDecoderFactory();
      c.decoder_map.emplace(kOpusPt, w::SdpAudioFormat("opus", 48000, 2));
      if (s.red) c.decoder_map.emplace(kAudioRedPt, w::SdpAudioFormat("red", 48000, 2));
      // One sync group, so Call::ConfigureSync runs RtpStreamsSynchronizer on the pair (issue #77).
      if (s.av_sync) c.sync_group = "sm";
      audio_recv = recv_call->CreateAudioReceiveStream(std::move(c));
    }
    if (s.video) {
      w::VideoReceiveStreamInterface::Config c(&recv_transport);
      c.rtp.remote_ssrc = kVideoSsrc;
      // The receiver measures the RTT as a receive-only endpoint does: RRTR in its reports, DLRR in the sender's
      // (rtcp_sender.cc BuildExtendedReports, rtcp_receiver.cc HandleXrDlrrReportBlock). ModuleRtpRtcpImpl2::
      // PeriodicUpdate gives it to CallStats, which feeds VideoReceiveStream2::OnRttUpdate, so the jitter estimator's
      // RTT term and NackRequester see a round trip, as in a real call where the receiver also sends (issue #24).
      // Without it this one-way Call has no RTT at all, while the test bench gives its receiver the sender's.
      c.rtp.rtcp_xr.receiver_reference_time_report = true;
      if (s.nack) {
        c.rtp.nack.rtp_history_ms = 1000;
        c.rtp.rtx_ssrc = kRtxSsrc;
        c.rtp.rtx_associated_payload_types[kRtxPt] = kVideoPt;
      }
      if (s.fec) {
        c.rtp.red_payload_type = kRedPt;
        c.rtp.ulpfec_payload_type = kUlpfecPt;
        if (s.nack) c.rtp.rtx_associated_payload_types[kRtxRedPt] = kRedPt;
      }
      c.decoder_factory = &decoder_factory;
      c.decoders.push_back(w::VideoReceiveStreamInterface::Decoder(ModelH264Format(), kVideoPt));
      c.renderer = &renderer;
      if (s.av_sync) c.sync_group = "sm";
      video_recv = recv_call->CreateVideoReceiveStream(std::move(c));
    }
  });
  run_on(receiver_q.get(), [&] {
    if (audio_recv) audio_recv->Start();
    if (video_recv) video_recv->Start();
    recv_call->SignalChannelNetworkState(w::MediaType::AUDIO, w::kNetworkUp);
    recv_call->SignalChannelNetworkState(w::MediaType::VIDEO, w::kNetworkUp);
  });
  run_on(sender_q.get(), [&] {
    send_call->SignalChannelNetworkState(w::MediaType::AUDIO, w::kNetworkUp);
    send_call->SignalChannelNetworkState(w::MediaType::VIDEO, w::kNetworkUp);
    if (audio_send) audio_send->Start();
    if (video_send) video_send->Start();
    // The route (and its transport overhead) arrives after the streams start, as in a
    // call where ICE/DTLS connects after negotiation (issue #196). With the route first,
    // AudioSendStream::Start registers with BitrateAllocator before it knows the 28 B,
    // and the allocator's synchronous OnBitrateUpdated updates overhead_per_packet_
    // before registered_with_allocator_ is set (audio_send_stream.cc
    // ConfigureBitrateObserver, UpdateOverheadPerPacket), so the allocator kept
    // reserving 32 kbps + 20 B / 20 ms = 40 kbps for the whole call while the stream
    // used 32 kbps + 48 B / 20 ms = 51.2 kbps. Now OnTransportOverheadChanged
    // reallocates and audio re-registers with 48 B.
    w::NetworkRoute route;
    route.connected = true;
    route.packet_overhead = static_cast<int>(kUdpIpOverhead);
    send_call->GetTransportControllerSend()->OnNetworkRouteChanged("sm-link", route);
  });

  // --- Media and network, stepped every 1 ms like testbench/call.cc ----------
  std::vector<float> speech;
  if (s.audio) speech = sim::SpeechLike(kAudioRate, s.duration.seconds() + 1, s.seed + 7, true);
  const int64_t end_ms = s.duration.ms();
  int64_t next_frame_ms = 0;
  double cross_debt = 0;
  bool stopping = false;
  int64_t last_bwe_target_bps = -1;  // Last target written to rep.bwe_trace (issue #149).
  // Counters at the last per-second video trace row (issue #131).
  struct VideoTracePrev {
    int64_t captured = 0, encoded = 0;
    uint32_t capturer = 0, queue = 0, rate = 0, cwnd = 0, encoder = 0;
    int64_t bytes = 0, qp_sum = 0, encode_us_sum = 0, height_sum = 0;
    int64_t keyframes = 0, keyframe_bytes = 0;
  } vt_prev;

  std::function<void(int64_t)> tick = [&](int64_t t) {
    if (stopping || t >= end_ms) return;
    const sm::Timestamp now = sm::Timestamp::Millis(t);

    advance_links(now);

    // Capture.
    if (s.audio && t % 10 == 0) {
      int16_t pcm[kAudioBlock];
      size_t off = static_cast<size_t>(t) * kAudioBlock / 10;
      for (int i = 0; i < kAudioBlock; ++i) {
        float v = off + static_cast<size_t>(i) < speech.size() ? speech[off + static_cast<size_t>(i)] : 0.f;
        pcm[i] = static_cast<int16_t>(std::clamp(v, -1.f, 1.f) * 32767);
      }
      uint32_t mic = 0;
      send_audio_state->audio_transport()->RecordedDataIsAvailable(pcm, kAudioBlock, 2, 1, kAudioRate, 0, 0, 0, false,
                                                                    mic);
    }
    if (s.video && t >= next_frame_ms) {
      ++model.frames_captured;
      model.encoder_rate_bps_sum += model.encoder_rate_bps;
      next_frame_ms = (model.frames_captured) * 1000 / s.video_fps;
      source.Capture(sim.Now().us());
    }
    if (fwd_state.cross.bps() > 0) {
      cross_debt += static_cast<double>(fwd_state.cross.bps()) / 8 / 1000;
      while (cross_debt >= 1200) {
        cross_debt -= 1200;
        forward.Send(now, Pkt{{}, false, true}, DataSize::Bytes(1200));
      }
    }

    // Deliver what arrives by the next tick, each packet at its own arrival time (issue #453). SimTime runs its
    // queues in creation order, so a packet that arrived during the last millisecond and was posted at this tick
    // reached the receiver after its timers due at this millisecond had run: libwebrtc's transport feedback at
    // 200 ms left out a packet that arrived at 199.3 ms, which a real receiver (and this library's, which takes the
    // tick's packets before its Process) reports. The packet is still counted here, at the tick before it arrives.
    auto post_at = [&](w::TaskQueueBase* q, w::Timestamp at_w, absl::AnyInvocable<void() &&> task) {
      const w::TimeDelta delay = at_w - sim.Now();
      if (delay > w::TimeDelta::Zero()) {
        q->PostDelayedHighPrecisionTask(std::move(task), delay);
      } else {
        q->PostTask(std::move(task));
      }
    };
    const sm::Timestamp horizon = now + sm::TimeDelta::Millis(1);
    forward.ReceiveEach(horizon, [&](Pkt p, sm::Timestamp at) {
      if (p.cross) return;
      const w::Timestamp at_w = t0 + w::TimeDelta::Micros(at.us());
      if (p.rtcp) {
        post_at(receiver_q.get(), at_w,
                [&, buf = w::CopyOnWriteBuffer(p.data)] { recv_call->Receiver()->DeliverRtcpPacket(buf); });
        return;
      }
      RtpInfo r = ParseRtp(p.data);
      if (!r.ok) return;
      const int64_t wire = static_cast<int64_t>(p.data.size()) + kUdpIpOverhead;
      if (r.payload_len > 0) {
        // Each media sequence number counts once, as the test bench counts it (#329).
        bool first = true;
        if (r.ssrc == kAudioSsrc) {
          first = first_delivery.Deliver(testbench::FirstDelivery::kAudio, r.seq);
        } else if (r.ssrc == kVideoSsrc) {
          first = first_delivery.Deliver(testbench::FirstDelivery::kVideo, r.seq);
        } else if (r.ssrc == kRtxSsrc) {
          // RTX with only its original sequence number is padding.
          const uint8_t* osn = p.data.data() + r.payload_off;
          first = r.payload_len > 2 &&
                  first_delivery.Deliver(testbench::FirstDelivery::kVideo, static_cast<uint16_t>((osn[0] << 8) | osn[1]));
        }
        if (first) w_good += wire;
      }
      if (r.ssrc == kAudioSsrc) {
        // From the capture time of the packet's first sample, as the test bench measures (its frame k has RTP
        // time 20k ms and leaves the encoder at 20k + 10 ms). The capture loop hands the ADM speech[t, t + 10)
        // at t, so the first packet holds the blocks of 0 and 10 ms and completes at 10 ms, and a packet's first
        // sample was captured at (ts - first ts) / 48 ms. Both stacks put audio on the link at 10 ms mod 20.
        // Padding on the audio SSRC carries no audio and gives no sample (#783).
        if (audio_ts0 && !audio_net_delay.started()) audio_net_delay.Start(*audio_ts0, kAudioRate);
        audio_net_delay.OnArrival(r.ts, /*carries_audio=*/r.payload_len > 0, at);
      } else if (r.ssrc == kVideoSsrc && r.payload_len > 0) {
        bool fec = r.pt == kRedPt && (p.data[r.payload_off] & 0x7f) == kUlpfecPt;
        if (!fec) {
          repair.OnVideoArrived(r.seq);
          frame_complete(r.ts, at);
        }
        if (fec_tap && r.pt == kRedPt) {
          w::RtpPacketReceived red(&extension_map, at_w);
          if (red.Parse(p.data.data(), p.data.size()) && fec_tap->AddReceivedRedPacket(red)) fec_tap->ProcessReceivedFec();
        }
      } else if (r.ssrc == kRtxSsrc && r.payload_len > 2) {
        repair.OnRtxArrived(static_cast<uint16_t>((p.data[r.payload_off] << 8) | p.data[r.payload_off + 1]));
        frame_complete(r.ts, at);
      }
      w::MediaType media = r.ssrc == kAudioSsrc ? w::MediaType::AUDIO : w::MediaType::VIDEO;
      post_at(receiver_q.get(), at_w, [&, media, at_w, buf = w::CopyOnWriteBuffer(p.data)] {
        w::RtpPacketReceived packet(&extension_map, at_w);
        if (!packet.Parse(buf)) return;
        // As WebRtcVideoReceiveChannel::OnPacketReceived (webrtc_video_engine.cc:3425); the voice channel sets none.
        // Without it a video stream with no RTX (NACK off) fails the RTC_CHECK in ReceiveStatistics'
        // IsRetransmitOfOldPacket (video_receive_stream2.cc:318 enables that detection), and the RR jitter is 0.
        if (media == w::MediaType::VIDEO) packet.set_payload_type_frequency(90000);
        recv_call->Receiver()->DeliverRtpPacket(media, std::move(packet),
                                                [](const w::RtpPacketReceived&) { return false; });
        // The first packet NetEq took (issue #510), as the test bench reads its jitter buffer right after the packet.
        if (media == w::MediaType::AUDIO && audio_recv && !audio_first.started()) {
          const w::AudioReceiveStreamInterface::Stats st = audio_recv->GetStats(false);
          audio_first.OnAudioPacket(rel(at_w), st.jitter_buffer_ms > 0 || st.total_samples_received > 0);
        }
      });
    });
    reverse.ReceiveEach(horizon, [&](Pkt p, sm::Timestamp at) {
      if (p.cross || !p.rtcp) return;
      if (opt.link_trace) testbench::TraceAudioRtcp(p.data, at.us(), kAudioSsrc, rep.audio_send_trace);
      testbench::TraceAudioRtcp(p.data, at.us(), kAudioSsrc, audio_reports);  // rtcp.audio_report_blocks (issue #484).
      post_at(sender_q.get(), t0 + w::TimeDelta::Micros(at.us()),
              [&, buf = w::CopyOnWriteBuffer(p.data)] {
                if (opt.link_trace) rtx_ack.OnRtcp(std::span<const uint8_t>(buf.cdata(), buf.size()));
                send_call->Receiver()->DeliverRtcpPacket(buf);
              });
    });

    // Receive-side frame counters once per second (issue #437), read on the receiver's queue: frames inserted into
    // the frame buffer (received_frame_counts, from OnCompleteFrame), decoded and dropped.
    if (opt.video_trace && video_recv && t % 1000 == 999) {
      receiver_q->PostTask([&, t_ms = t + 1] {
        w::VideoReceiveStreamInterface::Stats st = video_recv->GetStats();
        const int64_t complete = st.received_frame_counts.key_frames + st.received_frame_counts.delta_frames;
        rx_by_second.push_back(
            {t_ms, complete, static_cast<int64_t>(st.frames_decoded), static_cast<int64_t>(st.frames_dropped)});
      });
    }

    // Audio playout: the device pulls 10 ms.
    if (s.audio && t % 10 == 0) {
      receiver_q->PostTask([&, t_ms = t] {
        int16_t out[kAudioBlock * 2];
        size_t n_out = 0;
        int64_t elapsed = 0, ntp = 0;
        recv_audio_state->audio_transport()->NeedMorePlayData(kAudioBlock, 2, 1, kAudioRate, out, n_out, &elapsed,
                                                              &ntp);
        w::AudioReceiveStreamInterface::Stats st = audio_recv->GetStats(false);
        audio_buffer_ms = st.jitter_buffer_ms;
        // The audio playout point libwebrtc's own A/V sync reads (issue #63): RtpStreamsSynchronizer takes it from
        // Syncable::GetPlayoutRtpTimestamp (rtp_streams_synchronizer2.cc UpdateDelay), which AudioReceiveStreamImpl
        // implements. Its time is when the RTP timestamp was sampled.
        const w::Syncable* syncable = static_cast<const w::AudioReceiveStreamImpl*>(audio_recv);
        if (std::optional<w::Syncable::PlayoutInfo> pi = syncable->GetPlayoutRtpTimestamp(); pi && audio_ts0) {
          const int64_t samples = static_cast<int64_t>(static_cast<uint32_t>(pi->rtp_timestamp - *audio_ts0));
          av_sync.OnAudioPlayout(rel(pi->time), sm::Timestamp::Micros(samples * 1000 / 48));
        }
        // Playout statistics count from the first pull that output samples, as the test bench's (#510).
        if (!stretch.OnPull(st.total_samples_received, st.inserted_samples_for_deceleration,
                            st.removed_samples_for_acceleration)) {
          return;
        }
        uint64_t total = st.total_samples_received - prev_audio.total_samples_received;
        uint64_t concealed = st.concealed_samples - prev_audio.concealed_samples;
        uint64_t emitted = st.jitter_buffer_emitted_count - prev_audio.jitter_buffer_emitted_count;
        if (emitted > 0) {
          jb_delay.push_back((st.jitter_buffer_delay_seconds - prev_audio.jitter_buffer_delay_seconds) * 1000.0 /
                             static_cast<double>(emitted));
        }
        if (opt.audio_trace) {
          // Issue #62: the jitter buffer after each pull, in the test bench's AudioTraceRow layout. NetEq counts
          // samples at the decoder's 48 kHz (Opus).
          constexpr double kMsPerSample = 1000.0 / 48000;
          testbench::AudioTraceRow r;
          r.t_ms = t_ms;
          r.buffer_ms = static_cast<int>(st.jitter_buffer_ms);
          r.target_ms = static_cast<int>(st.jitter_buffer_preferred_ms);
          if (emitted > 0) r.jb_delay_ms = jb_delay.back();
          r.received_ms = static_cast<double>(total) * kMsPerSample;
          r.concealed_ms = static_cast<double>(concealed) * kMsPerSample;
          r.accelerate_ms =
              static_cast<double>(st.removed_samples_for_acceleration - prev_audio.removed_samples_for_acceleration) *
              kMsPerSample;
          r.decelerate_ms =
              static_cast<double>(st.inserted_samples_for_deceleration - prev_audio.inserted_samples_for_deceleration) *
              kMsPerSample;
          rep.audio_trace.push_back(r);
        }
        prev_audio = st;
        concealment.OnPull(st.total_samples_received, st.concealed_samples, st.concealment_events);
        w_played += concealment.pull_total();
        w_conceal += concealment.pull_concealed();
      });
    }

    // Measurement.
    double queue_ms = testbench::QueueDelayMs(forward, fwd_state, now);
    if (t % 10 == 0) queue_samples.push_back(queue_ms);
    if (t % 100 == 99) {
      Sample smp;
      smp.t_s = static_cast<double>(t + 1) / 1000.0;
      smp.capacity_kbps = fwd_state.cfg.down ? 0 : fwd_state.cfg.capacity.IsFinite() ? fwd_state.cfg.capacity.kbps() : -1;
      smp.send_kbps = static_cast<double>(w_send) * 8 / 100;
      smp.goodput_kbps = static_cast<double>(w_good) * 8 / 100;
      smp.queue_ms = queue_ms;
      smp.audio_buffer_ms = audio_buffer_ms;
      smp.audio_concealed_pct = w_played ? 100.0 * static_cast<double>(w_conceal) / static_cast<double>(w_played) : 0;
      smp.video_fps = static_cast<double>(w_frames) * 10;
      smp.video_delay_ms = last_video_delay;
      w_send = w_good = w_frames = w_conceal = w_played = 0;
      sender_q->PostTask([&, smp]() mutable {
        w::Call::Stats cs = send_call->GetStats();
        smp.target_kbps = static_cast<double>(cs.send_bandwidth_bps) / 1000.0;
        if (opt.bwe_trace && cs.send_bandwidth_bps != last_bwe_target_bps) {
          // The Call's target (Call::Stats::send_bandwidth_bps), sampled every 100 ms, when it changed.
          cc::BweTraceRow r;
          r.time_us = static_cast<int64_t>(smp.t_s * 1e6 + 0.5);
          r.kind = cc::BweTraceRow::Kind::kTarget;
          r.bitrate_bps = cs.send_bandwidth_bps;
          rep.bwe_trace.push_back(r);
          last_bwe_target_bps = cs.send_bandwidth_bps;
        }
        if (opt.video_trace && video_send && static_cast<int64_t>(smp.t_s * 1000 + 0.5) % 1000 == 0) {
          // Once per simulated second (issue #131): VideoSendStream::Stats counters, as deltas.
          w::VideoSendStream::Stats vs = video_send->GetStats();
          VideoTraceRow r;
          r.t_ms = static_cast<int64_t>(smp.t_s * 1000 + 0.5);
          r.encoder_target_bps = model.encoder_rate_bps;
          r.alloc_target_bps = vs.target_media_bitrate_bps;
          r.captured = static_cast<int>(model.frames_captured - vt_prev.captured);
          r.encoded = static_cast<int>(model.frames_encoded - vt_prev.encoded);
          r.dropped_capturer = static_cast<int>(vs.frames_dropped_by_capturer - vt_prev.capturer);
          r.dropped_encoder_queue = static_cast<int>(vs.frames_dropped_by_encoder_queue - vt_prev.queue);
          r.dropped_rate_limiter = static_cast<int>(vs.frames_dropped_by_rate_limiter - vt_prev.rate);
          r.dropped_congestion_window = static_cast<int>(vs.frames_dropped_by_congestion_window - vt_prev.cwnd);
          r.dropped_encoder = static_cast<int>(vs.frames_dropped_by_encoder - vt_prev.encoder);
          r.paused = vs.suspended ? 1 : 0;
          r.encoded_bytes = model.bytes - vt_prev.bytes;
          r.qp_sum = model.qp_sum - vt_prev.qp_sum;
          r.encode_us_sum = model.encode_us_sum - vt_prev.encode_us_sum;
          r.height_sum = model.height_sum - vt_prev.height_sum;
          r.pacer_queue_ms = static_cast<double>(cs.pacer_delay_ms);
          if (r.encoded > 0) {
            r.encode_width = model.last_width;
            r.encode_height = model.last_height;
          }
          r.keyframes = static_cast<int>(model.keyframes - vt_prev.keyframes);
          r.keyframe_bytes = model.keyframe_bytes - vt_prev.keyframe_bytes;
          vt_prev = {model.frames_captured, model.frames_encoded, vs.frames_dropped_by_capturer, vs.frames_dropped_by_encoder_queue,
                     vs.frames_dropped_by_rate_limiter, vs.frames_dropped_by_congestion_window,
                     vs.frames_dropped_by_encoder, model.bytes, model.qp_sum, model.encode_us_sum, model.height_sum,
                     model.keyframes, model.keyframe_bytes};
          rep.video_trace.push_back(r);
        }
        smp.rtt_ms = cs.rtt_ms > 0 ? static_cast<double>(cs.rtt_ms) : 0;
        if (cs.rtt_ms > 0) rtt_samples.push_back(static_cast<double>(cs.rtt_ms));
        rep.timeseries.push_back(smp);
      });
    }
    net_q->PostDelayedHighPrecisionTask([&tick, t] { tick(t + 1); }, w::TimeDelta::Millis(1));
  };
  net_q->PostTask([&] { tick(0); });
  sim.RunUntil(t0 + w::TimeDelta::Millis(end_ms));
  qs_log.Stop();
  stopping = true;

  // --- Final stats and teardown ---------------------------------------------
  int64_t keyframe_requests = 0, undecodable = 0, late_discards = 0;
  run_on(sender_q.get(), [&] {
    if (video_send) {
      auto vs = video_send->GetStats();
      auto it = vs.substreams.find(kVideoSsrc);
      if (it != vs.substreams.end()) {
        keyframe_requests = it->second.rtcp_packet_type_counts.pli_packets + it->second.rtcp_packet_type_counts.fir_packets;
      }
    }
  });
  run_on(receiver_q.get(), [&] {
    if (video_recv) undecodable = video_recv->GetStats().frames_dropped;
    if (audio_recv) late_discards = static_cast<int64_t>(audio_recv->GetStats(false).packets_discarded);
  });
  run_on(sender_q.get(), [&] {
    if (audio_send) {
      audio_send->Stop();
      send_call->DestroyAudioSendStream(audio_send);
    }
    if (video_send) {
      video_send->Stop();
      send_call->DestroyVideoSendStream(video_send);
    }
    send_call.reset();
  });
  run_on(receiver_q.get(), [&] {
    if (audio_recv) {
      audio_recv->Stop();
      recv_call->DestroyAudioReceiveStream(audio_recv);
    }
    if (video_recv) {
      video_recv->Stop();
      recv_call->DestroyVideoReceiveStream(video_recv);
    }
    recv_call.reset();
  });
  send_audio_state = nullptr;
  recv_audio_state = nullptr;
  rep.audio_send_trace.insert(rep.audio_send_trace.end(), opus_encode_rows.rows.begin(), opus_encode_rows.rows.end());
  sim.RunReady();

  // --- Summary (same definitions as testbench/call.cc) ------------------------
  const sm::Timestamp end = sm::Timestamp::Millis(end_ms);
  auto& m = rep.metrics;
  concealment.Finish();
  if (s.audio) {
    m["audio.concealed_pct"] = concealment.concealed_pct();
    m["audio.interruptions"] = static_cast<double>(concealment.interruptions());
    m["audio.interruption_ms"] = static_cast<double>(concealment.interruption_ms());
    m["audio.longest_interruption_ms"] = static_cast<double>(concealment.longest_event_ms());
    m["audio.jb_delay_p50_ms"] = testbench::Percentile(jb_delay, 50);
    m["audio.jb_delay_p95_ms"] = testbench::Percentile(jb_delay, 95);
    m["audio.net_delay_p95_ms"] = testbench::Percentile(audio_net_delay.samples(), 95);
    m["audio.mouth_to_ear_p95_ms"] = m["audio.net_delay_p95_ms"] + m["audio.jb_delay_p95_ms"];
    m["audio.stretch_pct"] = stretch.stretch_pct();
    m["audio.late_discards"] = static_cast<double>(late_discards);
    m["audio.time_to_first_ms"] = audio_first.ms(end_ms);
  }
  if (s.video) {
    // The row ending at t_ms counts the frames rendered in [t_ms - 1000, t_ms), as the test bench does.
    for (VideoTraceRow& r : rep.video_trace) {
      const size_t sec = static_cast<size_t>(r.t_ms / 1000 - 1);
      if (sec < render_by_second.size()) {
        r.rendered = render_by_second[sec].rendered;
        r.max_render_gap_ms = render_by_second[sec].max_gap_ms;
      }
      // Receive-side frame counters as deltas over the second (issue #437).
      for (size_t i = 0; i < rx_by_second.size(); ++i) {
        if (rx_by_second[i].t_ms != r.t_ms) continue;
        const RxSecond prev = i > 0 ? rx_by_second[i - 1] : RxSecond{};
        r.rx_complete = static_cast<int>(rx_by_second[i].complete - prev.complete);
        r.rx_decoded = static_cast<int>(rx_by_second[i].decoded - prev.decoded);
        r.rx_dropped = static_cast<int>(rx_by_second[i].dropped - prev.dropped);
      }
      // The scaler checks in [t_ms - 1000, t_ms), as the test bench counts them (issue #347).
      for (const QualityScalerLog::Check& c : qs_log.checks) {
        if (c.time_us < (r.t_ms - 1000) * 1000 || c.time_us >= r.t_ms * 1000) continue;
        ++r.qs_checks;
        r.qs_qp_high = c.qp_high;
        r.qs_qp_low = c.qp_low;
        r.qs_drop_pct = c.drop_pct;
        r.qs_signal = c.signal;
      }
    }
    const auto& fz = freezes.stats();
    double freeze_count = static_cast<double>(fz.freeze_count);
    double freeze_total = fz.total_freezes_ms;
    double longest = fz.longest_freeze_ms;
    double frame_ms = 1000.0 / s.video_fps;
    // Pauses as libwebrtc's VideoQualityObserver counts them: a gap of 5 s or more is
    // a pause, not a freeze. One still in progress at the end of the call is counted
    // too, so a blackout that lasts to the end is visible.
    double pause_count = static_cast<double>(fz.pause_count);
    double pause_total = fz.total_pauses_ms;
    if (!last_render.IsFinite()) {
      freeze_count = 1;
      freeze_total = longest = static_cast<double>(end_ms);
    } else {
      double tail = static_cast<double>((end - last_render).us()) / 1000.0;
      if (tail > std::max(3 * frame_ms, frame_ms + 150)) {
        freeze_count += 1;
        freeze_total += tail;
      }
      longest = std::max(longest, tail);
      if (tail >= 5000) {
        pause_count += 1;
        pause_total += tail;
      }
    }
    m["video.frames_rendered"] = static_cast<double>(frames_rendered);
    m["video.render_fps"] = static_cast<double>(frames_rendered) / s.duration.seconds();
    m["video.render_ratio_pct"] =
        model.frames_encoded ? 100.0 * static_cast<double>(frames_rendered) / static_cast<double>(model.frames_encoded) : 0;
    m["video.freeze_count"] = freeze_count;
    m["video.freeze_total_ms"] = freeze_total;
    m["video.longest_freeze_ms"] = longest;
    m["video.pause_count"] = pause_count;
    m["video.pause_total_ms"] = pause_total;
    m["video.e2e_delay_p50_ms"] = testbench::Percentile(video_e2e, 50);
    m["video.e2e_delay_p95_ms"] = testbench::Percentile(video_e2e, 95);
    m["video.time_to_first_frame_ms"] = video_first.IsFinite() ? static_cast<double>(video_first.ms()) : static_cast<double>(end_ms);
    {
      std::vector<testbench::VideoFrameTimes> all;
      all.reserve(model.frame_times.size());
      for (const auto& [ts, ft] : model.frame_times) all.push_back(ft);
      testbench::AddVideoDelayMetrics(all, m);  // Issue #510: as testbench/call.cc.
    }
    if (s.audio) av_sync.AddMetrics(m);
    testbench::AddAvSyncToVideoTrace(av_sync, rep.video_trace);
    m["video.avg_kbps"] = static_cast<double>(model.bytes) * 8 / s.duration.seconds() / 1000;
    m["video.qp_mean"] =
        model.frames_encoded ? static_cast<double>(model.qp_sum) / static_cast<double>(model.frames_encoded) : 0;
    m["video.encode_height_mean"] =
        model.frames_encoded ? static_cast<double>(model.height_sum) / static_cast<double>(model.frames_encoded) : 0;
    m["video.keyframes"] = static_cast<double>(model.keyframes);
    m["video.keyframe_requests"] = static_cast<double>(keyframe_requests);
    m["video.encoder_dropped"] = static_cast<double>(model.frames_captured - model.frames_encoded);
    m["video.encoder_target_avg_kbps"] =
        model.frames_captured
            ? static_cast<double>(model.encoder_rate_bps_sum) / static_cast<double>(model.frames_captured) / 1000
            : 0;
    m["video.undecodable_frames"] = static_cast<double>(undecodable);
    m["repair.fec_recovered"] = fec_tap ? static_cast<double>(fec_tap->GetPacketCounter().num_recovered_packets) : 0;
  }

  const int64_t audio_frame_bytes = std::max<int64_t>(10, s.audio_bitrate.bps() / 8 / 50);
  const double audio_wire_kbps =
      s.audio ? static_cast<double>((audio_frame_bytes * (s.red ? 2 : 1) + 12 + 4 + kUdpIpOverhead) * 8 * 50) / 1000.0 : 0;
  std::sort(rep.timeseries.begin(), rep.timeseries.end(), [](const Sample& a, const Sample& b) { return a.t_s < b.t_s; });
  testbench::AddCcMetrics(s, (s.video ? s.video_max.kbps() : 0) + audio_wire_kbps, rep);
  m["cc.queue_p95_ms"] = testbench::Percentile(queue_samples, 95);
  m["cc.queue_max_ms"] = queue_samples.empty() ? 0 : *std::max_element(queue_samples.begin(), queue_samples.end());
  {
    size_t over = 0;
    for (double q : queue_samples) over += q > 200;
    m["cc.queue_over_200ms_pct"] =
        queue_samples.empty() ? 0 : 100.0 * static_cast<double>(over) / static_cast<double>(queue_samples.size());
  }
  m["cc.rtt_p50_ms"] = testbench::Percentile(rtt_samples, 50);
  m["rtcp.audio_report_blocks"] = static_cast<double>(audio_reports.size());
  const auto& ls = forward.stats();
  m["net.loss_pct"] = ls.sent ? 100.0 * static_cast<double>(ls.lost + ls.queue_dropped) / static_cast<double>(ls.sent) : 0;
  testbench::AddLinkKindMetrics(ls, s, rep);
  if (opt.link_trace) rep.link_trace = forward.trace();
  if (opt.link_trace) rep.reverse_trace = reverse.trace();
  repair.AddMetrics(m, s.video, end_ms);

  testbench::EvaluateExpectations(rep);
  if (!opt.timeseries) rep.timeseries.clear();
  return rep;
}

