// The friend that GoogCcNetworkController, DelayBasedBwe and TrendlineEstimator declare for
// libwebrtc's own state printer (goog_cc/test/goog_cc_printer.cc, which the prebuilt does not
// contain). Read-only access to the live detector, for the detector rows (issue #152).
class GoogCcStatePrinter {
 public:
  static const DelayBasedBwe* Delay(const NetworkControllerInterface* c) {
    return static_cast<const GoogCcNetworkController*>(c)->delay_based_bwe_.get();
  }
  // Without WebRTC-Bwe-SeparateAudioPackets (off by default) this is the video detector, a TrendlineEstimator.
  static const TrendlineEstimator* Detector(const DelayBasedBwe* d) {
    return static_cast<const TrendlineEstimator*>(d->active_delay_detector_);
  }
  static double ModifiedTrend(const TrendlineEstimator* t) { return t->prev_modified_trend_; }
  static double Threshold(const TrendlineEstimator* t) { return t->threshold_; }
  static int NumDeltas(const TrendlineEstimator* t) { return t->num_of_deltas_; }
};
