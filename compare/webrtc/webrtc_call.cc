struct VideoModel {
  const Scenario* s = nullptr;
  Random rng;
  int64_t frames_captured = 0, frames_encoded = 0, keyframes = 0, bytes = 0;
  int64_t qp_sum = 0, encode_us_sum = 0;  // testbench/encoder_model.h (issue #84).
  int64_t last_key_us = INT64_MIN / 2;
  int64_t encoder_rate_bps = 0;  // Last SetRates (issue #131 trace).
  std::unordered_map<uint32_t, int64_t> capture_us_by_rtp;  // Filled by the decoder.
};

// Frame sizes follow the allocated rate with +-20% variation and keyframes
// are 4x larger, as in testbench/call.cc. The capture time travels in the
// first 8 payload bytes so the receiver can measure capture-to-render delay.
// QP (EncodedImage::qp_) and the encode time (timing_) come from the encoder
// model the test bench uses (testbench/encoder_model.h, issue #84).
class ModelEncoder final : public w::VideoEncoder {
 public:
  explicit ModelEncoder(VideoModel* m) : m_(m) {}
  int InitEncode(const w::VideoCodec*, const Settings&) override { return WEBRTC_VIDEO_CODEC_OK; }
  int32_t RegisterEncodeCompleteCallback(w::EncodedImageCallback* cb) override {
    cb_ = cb;
    return WEBRTC_VIDEO_CODEC_OK;
  }
  int32_t Release() override {
    cb_ = nullptr;
    return WEBRTC_VIDEO_CODEC_OK;
  }
  void SetRates(const RateControlParameters& p) override {
    rate_bps_ = p.bitrate.get_sum_bps();
    m_->encoder_rate_bps = rate_bps_;
  }
  int32_t Encode(const w::VideoFrame& frame, const std::vector<w::VideoFrameType>* types) override {
    if (!cb_) return WEBRTC_VIDEO_CODEC_UNINITIALIZED;
    const int64_t capture_us = frame.timestamp_us();
    bool key = types && !types->empty() && (*types)[0] == w::VideoFrameType::kVideoFrameKey;
    if (m_->s->keyframe_interval.us() > 0 && capture_us - m_->last_key_us >= m_->s->keyframe_interval.us()) key = true;
    double per_frame = static_cast<double>(rate_bps_) / 8 / m_->s->video_fps;
    int64_t bytes = static_cast<int64_t>(key ? per_frame * 4 : per_frame * m_->rng.Uniform(0.8, 1.2));
    bytes = std::max<int64_t>(bytes, 200);
    auto buf = w::EncodedImageBuffer::Create(static_cast<size_t>(bytes));
    std::memset(buf->data(), 0, buf->size());
    std::memcpy(buf->data(), &capture_us, sizeof(capture_us));
    w::EncodedImage img;
    img.SetEncodedData(buf);
    img._frameType = key ? w::VideoFrameType::kVideoFrameKey : w::VideoFrameType::kVideoFrameDelta;
    img._encodedWidth = static_cast<uint32_t>(frame.width());
    img._encodedHeight = static_cast<uint32_t>(frame.height());
    img.SetRtpTimestamp(frame.rtp_timestamp());
    img.capture_time_ms_ = frame.render_time_ms();
    img.qp_ = testbench::EncoderModel::Qp(bytes, key, frame.width(), frame.height(), m_->s->video_complexity);
    const int64_t encode_us = testbench::EncoderModel::EncodeTimeUs(frame.width(), frame.height(), m_->s->encoder_speed);
    img.timing_.flags = w::VideoSendTiming::kNotTriggered;
    img.timing_.encode_start_ms = capture_us / 1000;
    img.timing_.encode_finish_ms = (capture_us + encode_us) / 1000;
    m_->qp_sum += img.qp_;
    m_->encode_us_sum += encode_us;
    w::CodecSpecificInfo info;
    info.codecType = w::kVideoCodecGeneric;
    ++m_->frames_encoded;
    m_->bytes += bytes;
    if (key) {
      ++m_->keyframes;
      m_->last_key_us = capture_us;
    }
    cb_->OnEncodedImage(img, &info);
    return WEBRTC_VIDEO_CODEC_OK;
  }
  EncoderInfo GetEncoderInfo() const override {
    EncoderInfo info;
    info.implementation_name = "sm-encoder-model";
    // Like a software encoder: libwebrtc's frame dropper corrects overshoot,
    // as the test bench's frame dropper does.
    info.has_trusted_rate_controller = false;
    info.is_hardware_accelerated = false;
    info.scaling_settings = ScalingSettings::kOff;
    return info;
  }

 private:
  VideoModel* m_;
  w::EncodedImageCallback* cb_ = nullptr;
  uint32_t rate_bps_ = 0;
};

class ModelDecoder final : public w::VideoDecoder {
 public:
  explicit ModelDecoder(VideoModel* m) : m_(m), buffer_(w::I420Buffer::Create(320, 180)) {
    w::I420Buffer::SetBlack(buffer_.get());
  }
  bool Configure(const Settings&) override { return true; }
  int32_t Decode(const w::EncodedImage& img, int64_t render_time_ms) override {
    if (img.size() >= sizeof(int64_t)) {
      int64_t capture_us = 0;
      std::memcpy(&capture_us, img.data(), sizeof(capture_us));
      m_->capture_us_by_rtp[img.RtpTimestamp()] = capture_us;
    }
    w::VideoFrame f = w::VideoFrame::Builder()
                          .set_video_frame_buffer(buffer_)
                          .set_rtp_timestamp(img.RtpTimestamp())
                          .set_timestamp_ms(render_time_ms)
                          .build();
    if (cb_) cb_->Decoded(f);
    return WEBRTC_VIDEO_CODEC_OK;
  }
  int32_t RegisterDecodeCompleteCallback(w::DecodedImageCallback* cb) override {
    cb_ = cb;
    return WEBRTC_VIDEO_CODEC_OK;
  }
  int32_t Release() override { return WEBRTC_VIDEO_CODEC_OK; }

 private:
  VideoModel* m_;
  w::scoped_refptr<w::I420Buffer> buffer_;
  w::DecodedImageCallback* cb_ = nullptr;
};

