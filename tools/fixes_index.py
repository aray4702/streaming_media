#!/usr/bin/env python3
"""Regenerates docs/fixes/README.md: the process text plus a table of every
fix record (docs/fixes/<issue>-<slug>.md), built from their front matter.

    python3 tools/fixes_index.py          # rewrite docs/fixes/README.md
    python3 tools/fixes_index.py --check  # exit 1 if it is out of date
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIR = ROOT / "docs" / "fixes"
REPO = "https://github.com/aray4702/streaming_media"

HEADER = """# Fix records

Every problem found in the library (an issue labelled `agent-found`, `bug`,
`ux` or `perf`) is fixed together with:

1. **A regression test.** `testbench/scenarios/issue_<N>_<slug>.scn` with
   `expect` lines that fail on the commit before the fix and pass after it,
   plus a unit or e2e test in `tests/` when the cause is in one module. The
   scenario then runs in CI forever (`ctest -L scenario`).
2. **A fix record.** `docs/fixes/<N>-<slug>.md`, from
   [TEMPLATE.md](TEMPLATE.md): the issue, root cause, fix, regression tests,
   and the results before and after.

CI (`fix-record` job, `tools/check_fix_record.py`) enforces both on every
PR that fixes such an issue, and checks that the new scenario fails when
run on the PR's base commit. See [program.md](../../program.md) section 6.5.

This index is generated by `tools/fixes_index.py`; do not edit it by hand.
If it conflicts during a rebase, rerun the script.

"""


def front_matter(path):
    text = path.read_text()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None
    fields = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            fields[k.strip()] = v.strip()
    return fields


def records():
    out = []
    for p in sorted(DIR.glob("*.md")):
        if p.name in ("README.md", "TEMPLATE.md"):
            continue
        fm = front_matter(p)
        if not fm or not fm.get("issue", "").isdigit():
            continue
        out.append((int(fm["issue"]), p.name, fm))
    return sorted(out)


def render():
    rows = records()
    s = HEADER
    if not rows:
        return s + "No fixes recorded yet.\n"
    s += "| Issue | Problem | Severity | Area | Regression tests | Record |\n|---|---|---|---|---|---|\n"
    for n, name, fm in rows:
        tests = ", ".join(f"`{t.strip()}`" for t in fm.get("regression_tests", "").split(",") if t.strip())
        s += (f"| [#{n}]({REPO}/issues/{n}) | {fm.get('title', '')} | {fm.get('severity', '')} | "
              f"{fm.get('area', '')} | {tests} | [{name}]({name}) |\n")
    return s


def main():
    content = render()
    target = DIR / "README.md"
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != content:
            print("docs/fixes/README.md is out of date: run python3 tools/fixes_index.py", file=sys.stderr)
            return 1
        return 0
    DIR.mkdir(parents=True, exist_ok=True)
    target.write_text(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
