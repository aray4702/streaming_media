// The AI endpoint's media source for a two-way call (issue #4, part 1 of #758).
//
// An AI's speech (TTS) does not reach the sender at the steady real-time pace
// of a microphone. A model generates it faster than real time, in bursts with
// pauses while it computes, and only after a first-chunk delay. This model
// produces that schedule for one reply ("turn") and drains it into the call at
// real time (#4's option 1: no library change). It is the reference the
// send-ahead options of #4 (#762-#765) are measured against.
//
// Generation, for a reply that starts at `t0`:
//   - nothing comes out before t0 + first_chunk;
//   - then media comes out at `speed` x real time, `burst` of media at a time,
//     with a pause of `gap` after each burst (burst 0: one continuous burst);
//   - a frame (`frame` of media, 20 ms by default as the bench's audio) is
//     available once all of it has been generated.
//   So the end of the first m of media is generated at
//     t0 + first_chunk + b * (burst / speed + gap) + (m - b * burst) / speed,
//   with b = ceil(m / burst) - 1 the bursts completed before it.
//
// Draining at real time: the first frame is sent when it is generated, and
// each later one a frame length after the one before it, or when it is
// generated if that is later (an underrun: generation fell behind, and the
// receiver gets a gap). Frames wait in the app-side queue until then.
//
// Reported: how far the queue is ahead of real time (media generated but not
// yet sent), the time from the turn's start to its first frame sent, and the
// underruns. Deterministic: there is no randomness.
//
// Not wired into the call yet: part 2 of #758 does that once the two-way call
// exists (#746). `testbench/call.cc` does not read it, so one-way scenarios are
// unchanged.
#pragma once

#include <cstdint>
#include <deque>
#include <optional>
#include <vector>

#include "sm/core/units.h"

namespace sm::testbench {

// `ai_source speed=<x> burst=<time> gap=<time> first_chunk=<time> frame=<time>` (every key optional).
struct AiSourceConfig {
  double speed = 1;                                  // Generation speed, x real time (0.1..100).
  TimeDelta burst = TimeDelta::Zero();               // Media per burst; zero = one continuous burst.
  TimeDelta gap = TimeDelta::Zero();                 // Pause after each burst.
  TimeDelta first_chunk = TimeDelta::Zero();         // Turn start to the first media generated.
  TimeDelta frame = TimeDelta::Millis(20);           // Media per frame (the bench's audio frame).

  bool operator==(const AiSourceConfig&) const = default;
};

// The time after the turn's start at which the first `media` of the reply has been generated.
TimeDelta AiGenerationTime(const AiSourceConfig& config, TimeDelta media);

struct AiFrame {
  int64_t index = 0;                       // Frame number within the turn.
  TimeDelta media_offset;                  // Start of the frame within the reply.
  Timestamp generated = Timestamp::Micros(0);  // When the generator finished it.
  Timestamp send = Timestamp::Micros(0);       // When the real-time drain hands it to the sender.
  TimeDelta length;                        // Media in the frame (the reply's last frame may be shorter).
  bool late = false;                       // An underrun: sent after the previous frame plus its length.
  Timestamp handed = Timestamp::PlusInfinity();  // When Poll or TakeAhead handed it over (+inf: not yet).
};

struct AiSourceStats {
  int64_t turns = 0;
  int64_t frames_generated = 0;  // Counted when Poll reaches their generation time.
  int64_t frames_sent = 0;
  int64_t underruns = 0;         // Frames sent late because generation fell behind real time.
  TimeDelta max_queue_ahead = TimeDelta::Zero();
  int64_t cancels = 0;                       // Turns cut short by Cancel (barge-in, #760).
  TimeDelta cancelled = TimeDelta::Zero();   // Media dropped by them: not yet handed to the sender.
  std::optional<TimeDelta> first_frame_delay;  // Last turn: its start to its first frame sent.
};

class AiMediaSource {
 public:
  explicit AiMediaSource(const AiSourceConfig& config);

  // Starts a reply of `length` media at `now`. A turn still in progress is replaced.
  void StartTurn(Timestamp now, TimeDelta length);

  // The frames whose send time is at or before `now`, in order; they leave the queue.
  std::vector<AiFrame> Poll(Timestamp now);

  // Media generated by `now` and not yet sent: how far the queue is ahead of real time.
  TimeDelta QueueAhead(Timestamp now) const;

  // Send-ahead (#762): the frames generated by `now` that are due within `lead` of it, in order; they leave the queue
  // as Poll's do (counted as sent), handed to the sender early. Poll still returns the rest at their send times.
  std::vector<AiFrame> TakeAhead(Timestamp now, TimeDelta lead);
  // Barge-in (#760): stops generating the turn and drops its frames not yet handed to the sender. Frames already
  // polled stay sent. A turn with nothing left is unchanged.
  void Cancel(Timestamp now);
  // When the next frame is sent, if the turn has one left.
  std::optional<Timestamp> NextSendTime() const;

  bool active() const { return next_ < frames_.size(); }
  const AiSourceConfig& config() const { return config_; }
  const AiSourceStats& stats() const { return stats_; }

 private:
  AiSourceConfig config_;
  Timestamp turn_start_ = Timestamp::Micros(0);
  std::vector<AiFrame> frames_;  // The turn's whole schedule.
  size_t next_ = 0;              // First frame not yet sent.
  size_t generated_ = 0;         // Frames counted as generated in stats.
  AiSourceStats stats_;
  void CountGenerated(Timestamp now);
  void TakeNext(std::vector<AiFrame>& out, Timestamp now);
};

}  // namespace sm::testbench
